#!/usr/bin/env node
/**
 * 改行位置の微調整（フェーズ2 No.105〜107 の 2 巡目）
 *
 * 1 巡目の WrapText 適用後、狭い幅での実測でまだ残った症状を潰す。
 *   - 自分で置いた改行位置が助詞で終わっていた箇所を、文節の切れ目に寄せ直す
 *   - 狭い幅で語中が割れる長いセグメントを分割する
 *   - 和文と欧文が割れる箇所に WORD JOINER (U+2060) を入れて分断を防ぐ
 *
 * **文言は変更しない**（各置換で結合結果が元文字列と一致することを検証する）。
 *
 * 使い方:
 *   node scripts/check/tune-wraptext.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const FILE = "app/page.tsx";
const NL = "\\n";
const WJ = "⁠"; // WORD JOINER: 不可視。ここでは改行できなくなる
let s = readFileSync(FILE, "utf8");

const apply = (from, to, kind) => {
  const count = s.split(from).length - 1;
  if (count !== 1) {
    console.error(`一致数が ${count} 件（1 件であるべき）: ${from.slice(0, 46)}`);
    process.exit(1);
  }
  s = s.split(from).join(to);
  console.log(`  ${kind}: ${from.replace(/\\n/g, "|").slice(0, 46)}…`);
};

/** 改行位置の入れ替え。左右で文字列（改行指定を除く）が一致することを検証する。 */
const reseg = (fromSegs, toSegs, kind = "reseg") => {
  const plainFrom = fromSegs.join("");
  const plainTo = toSegs.join("");
  if (plainFrom !== plainTo) {
    console.error(`文言が変化しています:\n  ${plainFrom}\n  ${plainTo}`);
    process.exit(1);
  }
  apply(fromSegs.join(NL), toSegs.join(NL), kind);
};

/* ---- お客様の声：セグメント末尾が助詞にならないよう寄せ直す ---- */
reseg(
  ["工事が終わったあとも", "小さな相談に応えてもらえました。", "近くに頼れる方がいると思うと安心です。"],
  ["工事が終わったあとも小さな相談に", "応えてもらえました。", "近くに頼れる方がいると", "思うと安心です。"]
);
reseg(
  ["こちらの希望を急いで決めつけず、", "予算の中で優先した方がよいところを", "一緒に考えてくれました。"],
  ["こちらの希望を急いで決めつけず、", "予算の中で優先した方がよい", "ところを一緒に考えてくれました。"]
);
reseg(
  ["最初は費用がどこまで増えるのか不安でしたが、", "工事前に一つずつ説明してもらえたので、", "納得してお願いできました。"],
  ["最初は費用がどこまで", "増えるのか不安でしたが、", "工事前に一つずつ説明して", "もらえたので、納得してお願いできました。"]
);

/* ---- 見出し・リード文 ---- */
reseg(
  ["工事を終えたお客様から", "いただいた声をご紹介します。"],
  ["工事を終えたお客様から", "いただいた声を", "ご紹介します。"],
  "reseg(声リード)"
);

/* ---- 相談セクション ---- */
reseg(
  ["費用や工事内容で気になることがあれば、", "まずはご相談ください。", "まだ希望がまとまっていない段階でも大丈夫です。"],
  ["費用や工事内容で", "気になることがあれば、", "まずはご相談ください。", "まだ希望がまとまっていない", "段階でも大丈夫です。"]
);

/* ---- はじめてのリフォーム：360px で「お聞か / せください。」と語中が割れる ---- */
reseg(
  ["リフォームは、内容によって", "費用や工事期間、工事中の暮らし方が異なります。", "まずは気になる場所と、", "どんな暮らしにしたいかをお聞かせください。"],
  ["リフォームは、内容によって", "費用や工事期間、", "工事中の暮らし方が異なります。", "まずは気になる場所と、", "どんな暮らしにしたいかを", "お聞かせください。"]
);

/* ---- 特長パネル ---- */
reseg(
  ["ご希望とご予算を最初に整理し、", "必要な工事と選べる方法を丁寧にご説明します。", "工事が終わったあとも、住まいのことを", "気軽に相談できる関係を大切にしています。"],
  ["ご希望とご予算を最初に整理し、", "必要な工事と選べる方法を", "丁寧にご説明します。", "工事が終わったあとも、", "住まいのことを気軽に相談できる", "関係を大切にしています。"]
);

/* ---- 施工事例タイトル：和文と欧文の分断を WORD JOINER で防ぐ ---- */
apply(
  '"明るさと動線を見直した、家族が集まるLDK"',
  `"明るさと動線を見直した、家族が集まる${WJ}LDK"`,
  "word-joiner"
);

/* ---- FAQ の設問：360px で「いけません / か？」と割れる ---- */
apply(
  '"相談したら、すぐ契約しなければいけませんか？"',
  `"相談したら、すぐ契約しなければ${WJ}いけませんか？"`,
  "word-joiner"
);

writeFileSync(FILE, s);
console.log("\n[tune] 適用完了。文言の増減はありません。");
