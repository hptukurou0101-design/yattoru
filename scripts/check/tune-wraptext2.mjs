#!/usr/bin/env node
/**
 * 改行位置の再調整（フェーズ2 No.105〜107 の 3 巡目）
 *
 * 2 巡目で「狭い幅に収める」ことを優先して句読点以外の位置にも改行を入れた結果、
 * セグメント末尾が助詞になり「行末に助詞」が増えた。
 *
 * jp-typography スキルの原則に戻し、**改行位置は「。」「、」の直後だけ**にする。
 * 句読点の無い 1 文に無理な改行を入れると、必ず文節の途中で切れるため。
 *
 * **文言は変更しない**（各置換で結合結果が元文字列と一致することを検証する）。
 */
import { readFileSync, writeFileSync } from "node:fs";

const FILE = "app/page.tsx";
const NL = "\\n";
let s = readFileSync(FILE, "utf8");

const reseg = (fromSegs, toSegs) => {
  if (fromSegs.join("") !== toSegs.join("")) {
    console.error(`文言が変化しています:\n  ${fromSegs.join("")}\n  ${toSegs.join("")}`);
    process.exit(1);
  }
  const from = fromSegs.join(NL);
  const to = toSegs.join(NL);
  const count = s.split(from).length - 1;
  if (count !== 1) {
    console.error(`一致数が ${count} 件（1 件であるべき）: ${from.slice(0, 46)}`);
    process.exit(1);
  }
  s = s.split(from).join(to);
  // 改行位置が句読点の直後だけになっているか検証する
  for (const seg of toSegs.slice(0, -1)) {
    if (!/[。、]$/.test(seg)) {
      console.error(`句読点で終わっていないセグメント: 「${seg}」`);
      process.exit(1);
    }
  }
  console.log(`  ok: ${toSegs.map((t) => t.slice(0, 12)).join(" | ")}`);
};

/* 特長パネル */
reseg(
  ["ご希望とご予算を最初に整理し、", "必要な工事と選べる方法を", "丁寧にご説明します。", "工事が終わったあとも、", "住まいのことを気軽に相談できる", "関係を大切にしています。"],
  ["ご希望とご予算を最初に整理し、", "必要な工事と選べる方法を丁寧にご説明します。", "工事が終わったあとも、", "住まいのことを気軽に相談できる関係を大切にしています。"]
);

/* はじめてのリフォーム */
reseg(
  ["リフォームは、内容によって", "費用や工事期間、", "工事中の暮らし方が異なります。", "まずは気になる場所と、", "どんな暮らしにしたいかを", "お聞かせください。"],
  ["リフォームは、", "内容によって費用や工事期間、", "工事中の暮らし方が異なります。", "まずは気になる場所と、", "どんな暮らしにしたいかをお聞かせください。"]
);

/* お客様の声のリード文（句読点が無い 1 文なので改行指定を外し、自然折り返しに任せる） */
reseg(
  ["工事を終えたお客様から", "いただいた声を", "ご紹介します。"],
  ["工事を終えたお客様からいただいた声をご紹介します。"]
);

/* 声 1 */
reseg(
  ["最初は費用がどこまで", "増えるのか不安でしたが、", "工事前に一つずつ説明して", "もらえたので、納得してお願いできました。"],
  ["最初は費用がどこまで増えるのか不安でしたが、", "工事前に一つずつ説明してもらえたので、", "納得してお願いできました。"]
);

/* 声 2 */
reseg(
  ["こちらの希望を急いで決めつけず、", "予算の中で優先した方がよい", "ところを一緒に考えてくれました。"],
  ["こちらの希望を急いで決めつけず、", "予算の中で優先した方がよいところを一緒に考えてくれました。"]
);

/* 声 3 */
reseg(
  ["工事が終わったあとも小さな相談に", "応えてもらえました。", "近くに頼れる方がいると", "思うと安心です。"],
  ["工事が終わったあとも小さな相談に応えてもらえました。", "近くに頼れる方がいると思うと安心です。"]
);

/* 相談セクション */
reseg(
  ["費用や工事内容で", "気になることがあれば、", "まずはご相談ください。", "まだ希望がまとまっていない", "段階でも大丈夫です。"],
  ["費用や工事内容で気になることがあれば、", "まずはご相談ください。", "まだ希望がまとまっていない段階でも大丈夫です。"]
);

writeFileSync(FILE, s);
console.log("\n[tune2] 改行位置を句読点の直後だけに統一しました。文言の増減はありません。");
